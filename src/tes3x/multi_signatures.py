def find_multi_signature(image, name):
    """Locate an engine value, rejecting ambiguous or structurally different matches."""
    kind, offset, expected_section, prefix, signature = SIGNATURES[name]
    pattern = b"".join(b"." if token == "??" else re.escape(bytes.fromhex(token))
                       for token in signature.split())
    hits = list(re.finditer(pattern, image.data, re.S))
    if len(hits) != 1:
        raise ValueError("multiplayer %s: %d signatures, expected 1" % (name, len(hits)))
    at = hits[0].start() + offset
    if kind == "match":
        value = image.off_to_va(at)
        if value is None:
            raise ValueError("multiplayer %s: match is outside XBE sections" % name)
        if name == "CLASS_NEW":
            boundary = bytes(image.data[at - 3:at]) == b"\xC2\x04\x00"
        elif name == "BODY_PART_UPDATE":
            boundary = True  # embedded table in .text
        else:
            boundary = at > 0 and image.data[at - 1] in (0xCC, 0xC3)
        if not boundary:
            raise ValueError("multiplayer %s: not at a function entry" % name)
    else:
        if bytes(image.data[at - 3:at]).hex() != prefix:
            raise ValueError("multiplayer %s: unexpected operand instruction" % name)
        value = struct.unpack_from("<I", image.data, at)[0]
    section = next((s for s in image.sections if s.va <= value < s.va + s.vsize), None)
    if section is None or section.name != expected_section:
        raise ValueError("multiplayer %s: address is outside %s" % (name, expected_section))
    return value
