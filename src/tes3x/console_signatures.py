def find_console_signature(image, name):
    """Return a checked engine VA from a unique .text signature."""
    kind, offset, prefix, signature = SIGNATURES[name]
    text = next((s for s in image.sections if s.name == ".text"), None)
    if text is None:
        raise ValueError("console binding: no .text section")
    blob = bytes(image.data[text.raw:text.raw + text.rsize])
    pattern = b"".join(b"." if token == "??" else re.escape(bytes.fromhex(token))
                       for token in signature.split())
    hits = list(re.finditer(pattern, blob, re.S))
    if len(hits) != 1:
        raise ValueError("console %s: %d signatures, expected 1" % (name, len(hits)))
    at = hits[0].start() + offset
    if kind == "match":
        if at < 1 or blob[at - 1] not in (0xCC, 0xC3):
            raise ValueError("console %s: signature is not at a function entry" % name)
        value = text.va + at
        expected_section = ".text"
    else:
        if blob[at - 3:at] != bytes.fromhex(prefix):
            raise ValueError("console %s: unexpected address instruction" % name)
        value = struct.unpack_from("<I", blob, at)[0]
        expected_section = ".text" if name == "VK_CAPS" else ".data"
    section = next((s for s in image.sections if s.va <= value < s.va + s.vsize), None)
    if section is None or section.name != expected_section:
        raise ValueError("console %s: address is outside %s" % (name, expected_section))
    return value
